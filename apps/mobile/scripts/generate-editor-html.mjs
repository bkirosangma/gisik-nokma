#!/usr/bin/env node
// Bakes packages/editor's single-file webview bundle (dist-webview/index.html,
// gitignored build output) into a checked-in TS string constant. RN/Metro has
// no runtime filesystem access to source packages, so a WebView needs the
// HTML content as a JS value at bundle time, not a path to read later. Run
// this after `pnpm --filter @gisik-nokma/editor run build:webview` — before
// `expo start`/`expo run:*`, and again whenever `packages/editor`'s webview
// bundle changes. Not part of the gate: the declared test/typecheck surface
// never renders a real WebView, so a stale generated file cannot fail them —
// only a real device/simulator run would notice, and that is out of scope
// for this task.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const bundlePath = resolve(here, '../../../packages/editor/dist-webview/index.html');
const outPath = resolve(here, '../src/editor/editor-html.generated.ts');

let html;
try {
  html = readFileSync(bundlePath, 'utf8');
} catch (err) {
  console.error(
    `Could not read ${bundlePath}. Run "pnpm --filter @gisik-nokma/editor run build:webview" first.\n${err.message}`,
  );
  process.exitCode = 1;
  throw err;
}

const banner =
  '// GENERATED by apps/mobile/scripts/generate-editor-html.mjs from packages/editor\'s\n' +
  '// build:webview output. Do not hand-edit. Regenerate with:\n' +
  '//   pnpm --filter @gisik-nokma/editor run build:webview\n' +
  '//   node apps/mobile/scripts/generate-editor-html.mjs\n';
writeFileSync(outPath, `${banner}export const EDITOR_HTML: string = ${JSON.stringify(html)};\n`);
console.log(`Wrote ${outPath} (${html.length} bytes of bundled HTML).`);
