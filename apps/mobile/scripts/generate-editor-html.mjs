#!/usr/bin/env node
// Bakes packages/editor's single-file webview bundle (dist-webview/index.html,
// gitignored build output) into a checked-in TS string constant. RN/Metro has
// no runtime filesystem access to source packages, so a WebView needs the
// HTML content as a JS value at bundle time, not a path to read later. Run
// this after `pnpm --filter @gisik-nokma/editor run build:webview` — before
// `expo start`/`expo run:*`, and again whenever `packages/editor`'s webview
// bundle changes.
//
// `--check` (ruling P30): regenerates the content in memory and diffs it
// against what is checked in, the same shape `scripts/help-content.mjs
// --check` uses for the in-app manual. It is wired as a step in
// `@gisik-nokma/mobile`'s `test` (package.json), so a bundle change that
// nobody regenerated for is caught by the gate instead of only a real
// device/simulator run noticing. When the bundle itself has not been built
// yet (`packages/editor/dist-webview/index.html` is gitignored build
// output, absent on a fresh checkout that has not run `build:webview`),
// `--check` cannot compare anything — it warns and exits 0 rather than
// failing every `pnpm test` that has not built the editor's webview bundle.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const BUNDLE_PATH = resolve(here, '../../../packages/editor/dist-webview/index.html');
export const OUT_PATH = resolve(here, '../src/editor/editor-html.generated.ts');

const BANNER =
  '// GENERATED by apps/mobile/scripts/generate-editor-html.mjs from packages/editor\'s\n' +
  '// build:webview output. Do not hand-edit. Regenerate with:\n' +
  '//   pnpm --filter @gisik-nokma/editor run build:webview\n' +
  '//   node apps/mobile/scripts/generate-editor-html.mjs\n';

export function generatedContent(html) {
  return `${BANNER}export const EDITOR_HTML: string = ${JSON.stringify(html)};\n`;
}

/**
 * @returns {{status: 'ok' | 'stale' | 'no-bundle', message: string}}
 */
export function checkFreshness(bundlePath, outPath) {
  if (!existsSync(bundlePath)) {
    return {
      status: 'no-bundle',
      message: `${bundlePath} does not exist — run "pnpm --filter @gisik-nokma/editor run build:webview" first. Freshness not checked.`,
    };
  }
  const expected = generatedContent(readFileSync(bundlePath, 'utf8'));
  const actual = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (expected === actual) {
    return { status: 'ok', message: `${outPath} matches the built bundle.` };
  }
  return {
    status: 'stale',
    message: `${outPath} is stale — the built bundle has changed since it was last generated. Run "node apps/mobile/scripts/generate-editor-html.mjs".`,
  };
}

/** `--bundle`/`--out` override the real paths — for the test suite only; the CLI's own regeneration always uses the real ones. */
function argValue(flag) {
  const i = process.argv.indexOf(flag);
  return i === -1 ? undefined : process.argv[i + 1];
}

function main() {
  const bundlePath = argValue('--bundle') ?? BUNDLE_PATH;
  const outPath = argValue('--out') ?? OUT_PATH;
  const check = process.argv.includes('--check');
  if (check) {
    const result = checkFreshness(bundlePath, outPath);
    if (result.status === 'stale') {
      console.error(`generate-editor-html --check: STALE — ${result.message}`);
      process.exitCode = 1;
      return;
    }
    console.log(`generate-editor-html --check: ${result.status} — ${result.message}`);
    return;
  }

  let html;
  try {
    html = readFileSync(bundlePath, 'utf8');
  } catch (err) {
    console.error(
      `Could not read ${bundlePath}. Run "pnpm --filter @gisik-nokma/editor run build:webview" first.\n${err.message}`,
    );
    process.exitCode = 1;
    throw err;
  }
  writeFileSync(outPath, generatedContent(html));
  console.log(`Wrote ${outPath} (${html.length} bytes of bundled HTML).`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
