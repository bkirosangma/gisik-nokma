import type { PoolClient } from 'pg';
import { docToPlainText, isRedactedTicketCreated, type LedgerEvent } from '@gisik-nokma/domain';
import { purgedResolverFor } from '../purge/purged-lookup.js';
import type { Projection } from './registry.js';

/**
 * Full-text search over titles, descriptions and comments (spec §7, Plan 5
 * Task 6), maintained as an ordinary projection.
 *
 * ## Visibility is a READ-time decision, deliberately
 *
 * This table stores EVERY ticket's text, the way proj_tickets stores every
 * ticket's state. The `/v1/search` route joins `visibleTicketsWhere` against
 * proj_visibility to decide who may see a hit. Filtering at index time would
 * bake a permission decision into a rebuildable table, and it would go stale
 * the moment an audience changed without a new ticket event.
 *
 * ## Determinism
 *
 * Every statement touches only the row of the event's OWN ticket, and reads no
 * other projection's table — it does read `purged_entities` (trash Plan 2, D2), which is not a projection, is never reset, and answers identically live and on rebuild, so a chip to an erased item renders `Deleted item` both ways — so per-entity `seq` order — the only ordering
 * replay guarantees — fully determines the result. No clock is read; the `tsv`
 * column is GENERATED by Postgres from the three text columns, so the
 * projection never writes it and never has to keep it in step.
 *
 * The one ordering this projection DOES depend on is its own entity's: comments
 * accumulate, so the concatenated text is in `seq` order per ticket. That is
 * exactly what canonical replay order `(entity_kind, entity_id, seq)` delivers,
 * and it is what makes a rebuild byte-identical to the live table rather than
 * merely equivalent.
 *
 * ## Why the text columns are kept beside the tsvector
 *
 * A `tsvector` cannot be read back into the words it came from, and the search
 * response carries a snippet. So the three sources are stored as text and the
 * index is derived from them, not the other way round.
 *
 * ## Unqualified table names
 *
 * `proj_search`, never `public.proj_search`: tools/verify-projections.ts fences
 * its rebuild inside a shadow schema with `search_path` ALONE, so a
 * schema-qualified name would escape the fence and write LIVE during a verify.
 */
export const searchProjection: Projection = {
  name: 'proj_search',
  tables: ['proj_search'],

  async apply(event: LedgerEvent, tx: PoolClient): Promise<void> {
    // All three types below are registered with `entityKind: 'ticket'`
    // (packages/domain/src/vocabulary.ts) and `parseEvent` refuses a mismatch,
    // so this guard is belt-and-braces rather than a reachable branch — kept
    // because `apply` is also called by replay paths that read the ledger
    // directly, and stated as redundant rather than dressed up as a rule.
    if (event.entity.kind !== 'ticket') {
      return;
    }

    if (event.type === 'ticket.created') {
      // Trash series Plan 2 (spec §5.4): a redacted creation has no title to
      // index — and `title` is NOT NULL, so indexing it would throw.
      if (isRedactedTicketCreated(event)) {
        return;
      }
      // `description` is optional on the payload (owner request 2026-09-23): the
      // New ticket dialog can compose one at creation. It is rendered by the
      // SAME `docToPlainText` the `ticket.field_set` branch below uses, so the
      // two doors cannot disagree about what a description is as search text —
      // and `docToPlainText` is TOTAL, so an ABSENT description (or a payload
      // older than the member, or a `null`) renders `''` rather than throwing
      // inside the ingest transaction. `''` is also the column's own default,
      // which is what this row used to get for want of the write at all.
      //
      // ⚠ MEASURED before this line existed: `proj_search.description` was
      // written by `ticket.field_set` ALONE, so a ticket created with a
      // description carried the document in head state while this column stayed
      // empty — the person found the ticket by its title and not by the words
      // they had just typed. `search-birth-description.test.ts` pins both halves,
      // including that a ticket born with NO description does not get the string
      // `'undefined'` indexed instead.
      const payload = event.payload as { projectId: string; title: string; description?: unknown };
      await tx.query(
        `INSERT INTO proj_search (ticket_id, workspace_id, project_id, title, description)
         VALUES ($1, $2, $3, $4, $5)`,
        [
          event.entity.id,
          event.workspaceId,
          payload.projectId,
          payload.title,
          docToPlainText(payload.description, { isPurged: await purgedResolverFor(tx, [payload.description]) }),
        ],
      );
      return;
    }

    if (event.type === 'ticket.field_set') {
      const payload = event.payload as { fieldId: string; value: unknown };
      if (payload.fieldId === 'title') {
        // A title claim whose value is not a string is IGNORED rather than
        // coerced. `ticketFieldSetPayload` admits any value at the door
        // (semantics are the engine's job), and `SET title = $2` with a number
        // would let node-pg render `42` into a text column — a title nobody
        // typed, in an append-only product's search index.
        if (typeof payload.value === 'string') {
          await tx.query('UPDATE proj_search SET title = $2 WHERE ticket_id = $1', [
            event.entity.id,
            payload.value,
          ]);
        }
        return;
      }
      if (payload.fieldId === 'description') {
        // `docToPlainText` is total: any unrenderable value — `null`, the
        // explicit CLEARING claim included — yields '', which is the honest
        // "there is no description text" and never a throw inside the ingest
        // transaction.
        await tx.query('UPDATE proj_search SET description = $2 WHERE ticket_id = $1', [
          event.entity.id,
          docToPlainText(payload.value, { isPurged: await purgedResolverFor(tx, [payload.value]) }),
        ]);
      }
      return;
    }

    if (event.type === 'comment.added') {
      const payload = event.payload as { body: unknown };
      const text = docToPlainText(payload.body, { isPurged: await purgedResolverFor(tx, [payload.body]) });
      // A comment that renders to nothing adds NOTHING — not even the
      // separator. Writing the separator anyway would leave a trailing newline
      // that a rebuild reproduces faithfully and that no comment accounts for.
      if (text.length === 0) {
        return;
      }
      await tx.query(
        `UPDATE proj_search
            SET comments = comments || CASE WHEN comments = '' THEN '' ELSE E'\\n' END || $2
          WHERE ticket_id = $1`,
        [event.entity.id, text],
      );
      return;
    }

    if (event.type === 'comment.edited' || event.type === 'comment.deleted') {
      // RE-DERIVED from the ledger up to THIS event's seq, so a rebuild (canonical replay order) and the
      // live ingest compute the same text at every step (case 26.048). Appending, as `comment.added`
      // does, cannot express "replace" or "remove". Note comments are in no index (`note-search.ts`).
      await tx.query('UPDATE proj_search SET comments = $2 WHERE ticket_id = $1', [
        event.entity.id,
        await ticketCommentText(tx, event.entity.id, event.seq),
      ]);
    }
  },

  async reset(tx: PoolClient): Promise<void> {
    await tx.query('TRUNCATE proj_search');
  },
};

/** The ticket's live comment text, oldest first, one line per non-empty comment — what `comment.added`'s appends build. */
async function ticketCommentText(tx: PoolClient, ticketId: string, uptoSeq: number): Promise<string> {
  const { rows } = await tx.query<{ id: string; type: string; payload: { body?: unknown; commentId?: string } }>(
    `SELECT id, type, payload FROM events
      WHERE entity_kind = 'ticket' AND entity_id = $1 AND seq <= $2
        AND type IN ('comment.added', 'comment.edited', 'comment.deleted')
      ORDER BY seq`,
    [ticketId, uptoSeq],
  );
  const bodies = new Map<string, unknown>();
  for (const row of rows) {
    if (row.type === 'comment.added') bodies.set(row.id, row.payload.body ?? null);
    else if (row.type === 'comment.edited' && row.payload.commentId !== undefined && bodies.has(row.payload.commentId)) {
      bodies.set(row.payload.commentId, row.payload.body ?? null);
    } else if (row.type === 'comment.deleted' && row.payload.commentId !== undefined) bodies.delete(row.payload.commentId);
  }
  const live = [...bodies.values()];
  const isPurged = await purgedResolverFor(tx, live);
  return live.map((body) => docToPlainText(body, { isPurged })).filter((t) => t.length > 0).join('\n');
}
