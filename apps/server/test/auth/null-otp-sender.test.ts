import { evaluateEvent } from '@gisik-nokma/rule-engine';
import type { FastifyInstance } from 'fastify';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { buildApp } from '../../src/app.js';
import { createAuth } from '../../src/auth/auth.js';
import { LogMagicLinkSender } from '../../src/auth/magic-link-sender.js';
import {
  LogOtpSender,
  NullOtpSender,
  PHONE_SIGN_IN_UNAVAILABLE,
  type OtpSender,
} from '../../src/auth/otp-sender.js';
import { createObjectStoreFromEnv } from '../../src/attachments/store-config.js';
import { createIngestService } from '../../src/ingest/ingest-service.js';
import { buildProjectionRegistry } from '../../src/projections/index.js';
import { createTestDatabase, type TestDatabase } from '../helpers/db.js';

/** Long enough that better-auth does not warn, and obviously not a credential. */
const TEST_SECRET = 'test-secret-not-used-anywhere-real';
const BASE_URL = 'http://localhost:3000';

let db: TestDatabase;
let refusing: FastifyInstance;
let logging: FastifyInstance;

/**
 * The REAL assembled server, over the real `/api/auth/*` mount — not a direct
 * call to `sender.send()`.
 *
 * That is the whole test. "The production OTP sender refuses" is easy to prove
 * as a rejected promise and worth nothing at that level: a rejection that
 * reaches better-auth as an ordinary `Error` comes back to the client as a 500
 * with an opaque body, which is an outage, not a refusal. What must be true is
 * that the answer on the wire carries a status and a code a client can render,
 * and only a request through the mount can say so.
 */
function buildServer(otpSender: OtpSender): FastifyInstance {
  const auth = createAuth({
    pool: db.pool,
    otpSender,
    magicLinkSender: new LogMagicLinkSender(() => {}),
    baseUrl: BASE_URL,
    secret: TEST_SECRET,
    // The browser's origin, so better-auth trusts the product's own client.
    webOrigin: 'http://localhost:3001',
  });
  const ingest = createIngestService({
    pool: db.pool,
    evaluate: evaluateEvent,
    projections: buildProjectionRegistry(),
  });
  return buildApp({
    db: db.pool,
    pool: db.pool,
    ingest,
    auth,
    serverAppend: (events) => ingest.ingestBatch(events),
    webOrigin: 'http://localhost:3001',
    store: createObjectStoreFromEnv({}),
  });
}

async function sendOtp(app: FastifyInstance, phone: string) {
  return app.inject({
    method: 'POST',
    url: '/api/auth/phone-number/send-otp',
    payload: { phoneNumber: phone },
  });
}

beforeAll(async () => {
  db = await createTestDatabase();
  refusing = buildServer(new NullOtpSender());
  logging = buildServer(new LogOtpSender(() => {}));
  await refusing.ready();
  await logging.ready();
});

afterAll(async () => {
  await refusing.close();
  await logging.close();
  await db.drop();
});

describe('phone sign-in with the production OTP sender', () => {
  /**
   * 13.148 — over the REAL mounted route (`app.inject` against `/api/auth/phone-number/send-otp`), the refusal is a 501 the client can render rather than a 500.
   */
  it('refuses in a shape the client can render, not as a 500', async () => {
    const response = await sendOtp(refusing, '+919000000101');

    expect(response.statusCode).toBe(501);
    const body = response.json() as { code?: string; message?: string };
    expect(body.code).toBe(PHONE_SIGN_IN_UNAVAILABLE);
    // A person, not a stack trace: the sentence has to point at the door that
    // IS open, or the refusal is an outage with better manners.
    expect(body.message).toContain('email');
    // The body is EXACTLY those two fields and nothing else.
    //
    // Written this way rather than as `expect(body).not.toMatch(/\d{6}/)`,
    // which is a check that cannot fail: the refusal message contains no digits
    // at all, so the regex is green whether or not a code could ever leak. What
    // is actually feared is a future "helpfully" verbose error growing a third
    // field — a `cause`, a debug payload — carrying the code the vendor has
    // already generated by this point in the request. An exact key set reddens
    // on any such field.
    expect(Object.keys(body).sort()).toEqual(['code', 'message']);
  });

  /**
   * 13.149 — the refusal never answers with the string `'code sent'` — a code nobody will receive must not be reported as sent.
   */
  it('never answers "code sent" for a code nobody will receive', async () => {
    const response = await sendOtp(refusing, '+919000000102');
    expect(response.body).not.toContain('code sent');
  });

  /**
   * 13.150 — the positive control that makes 13.148 mean something: the identical request against `LogOtpSender` succeeds. Without it, a 501 could come from the route being broken rather than from the sender refusing.
   */
  it('POSITIVE CONTROL: the same request succeeds on the dev sender', async () => {
    // Without this, the 501 above would be consistent with a mount that is
    // simply broken for this route. The ONLY difference between the two servers
    // is which `OtpSender` was passed in.
    const response = await sendOtp(logging, '+919000000104');
    expect(response.statusCode).toBe(200);
    expect(response.body).toContain('code sent');
  });
});
